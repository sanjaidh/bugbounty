const fs = require("fs");
const path = require("path");

const assetsDir = path.join(__dirname, "assets");
if (!fs.existsSync(assetsDir)) {
  fs.mkdirSync(assetsDir, { recursive: true });
}

// Generate a valid WAV file (Robot36 SSTV audio tone simulation)
function createSSTVWav() {
  const sampleRate = 44100;
  const durationSecs = 5;
  const numSamples = sampleRate * durationSecs;
  const dataSize = numSamples * 2; // 16-bit mono
  const buffer = Buffer.alloc(44 + dataSize);

  // RIFF header
  buffer.write("RIFF", 0);
  buffer.writeUInt32LE(36 + dataSize, 4);
  buffer.write("WAVE", 8);
  buffer.write("fmt ", 12);
  buffer.writeUInt32LE(16, 16); // Subchunk1Size
  buffer.writeUInt16LE(1, 20);  // AudioFormat (PCM)
  buffer.writeUInt16LE(1, 22);  // NumChannels (1)
  buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(sampleRate * 2, 28); // ByteRate
  buffer.writeUInt16LE(2, 32);  // BlockAlign
  buffer.writeUInt16LE(16, 34); // BitsPerSample
  buffer.write("data", 36);
  buffer.writeUInt32LE(dataSize, 40);

  // Generate Robot36 sync tones (1200 Hz sync, 1900 Hz data tones)
  for (let i = 0; i < numSamples; i++) {
    const t = i / sampleRate;
    const freq = (i % 8820 < 400) ? 1200 : 1900 + Math.sin(t * 50) * 400;
    const sample = Math.sin(2 * Math.PI * freq * t) * 0.5 * 32767;
    buffer.writeInt16LE(Math.floor(sample), 44 + i * 2);
  }

  return buffer;
}

const wavPath = path.join(assetsDir, "stage1_signal.wav");
fs.writeFileSync(wavPath, createSSTVWav());
console.log("✓ Created stage1_signal.wav at", wavPath);

